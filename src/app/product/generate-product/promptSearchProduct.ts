const formatSearchSources = (parseInfo: SearchSource[] = []): string => {
  if (parseInfo.length === 0) return "данных предварительного поиска нет";

  return parseInfo
    .map((el, i) => {
      const lines = [`${i + 1}. ${el.title || "Без заголовка"}`, `URL: ${el.url}`];
      if (el.content) lines.push(el.content);
      return lines.join("\n");
    })
    .join("\n\n");
};

